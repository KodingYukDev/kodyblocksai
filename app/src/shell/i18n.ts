export const MESSAGES: Record<AppLocale, Messages> = { id, en };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function makeTranslate(locale: AppLocale): Translate {
  const table = MESSAGES[locale];
  return (key, vars) => {
    let text: string = table[key];
    if (vars) {
      for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
    }
    return text;
  };
}

export const LocaleContext = createContext<Translate>(makeTranslate("id"));

export function useT(): Translate {
  return useContext(LocaleContext);
}
