export function msg(locale: Locale, key: MsgKey, ...args: string[]): string {
  let text: string = locale === "id" ? ID[key] : EN[key];
  args.forEach((a, i) => {
    text = text.replace(`%${i + 1}`, a);
  });
  return text;
}
